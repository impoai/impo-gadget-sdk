#!/usr/bin/env python3
"""Generate the checked-in ARCS Mini Status 24 bitmap font (Pillow is a dev tool)."""
import argparse, hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

TEXT = "".join(chr(i) for i in range(32,127)) + "MiniIMPO启动中等待配对连接待机我在听思考正在回答网络断开电量低充更新短按说话你好结束"
SHA256 = "a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da"
def generate(source, text=TEXT):
    if hashlib.sha256(source.read_bytes()).hexdigest() != SHA256:
        raise ValueError("Unexpected Noto Sans SC source")
    font = ImageFont.truetype(str(source), 22)
    font.set_variation_by_axes([500])
    lines = ["/* SPDX-License-Identifier: OFL-1.1",
             " * ARCS Mini Status 24, derived from Noto Sans SC; see LICENSE-OFL and NOTICE.",
             " * Generated by tools/gen_screen_font.py. Font source SHA256: " + SHA256,
             " */", "#pragma once", "#include <stdint.h>",
             "typedef struct { uint32_t codepoint; uint8_t advance; uint8_t bits[72]; } arcs_mini_glyph_t;",
             "static const arcs_mini_glyph_t arcs_mini_glyphs[] = {"]
    for char in sorted(set(text), key=ord):
        im = Image.new("L", (24, 24))
        draw = ImageDraw.Draw(im)
        l, t, r, b = font.getbbox(char)
        draw.text(((24-l-r)/2, (24-t-b)/2), char, font=font, fill=255)
        bits = []
        for y in range(24):
            for x in range(0, 24, 8):
                bits.append(sum((1 << (7-i)) if im.getpixel((x+i, y)) >= 100 else 0 for i in range(8)))
        advance = 24 if ord(char) >= 128 else 16
        lines.append("    {0x%x, %d, {%s}}, /* %s */" % (ord(char), advance, ",".join("0x%02x" % n for n in bits), char))
    lines += ["};", ""]
    return "\n".join(lines)

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("font", type=Path)
    ap.add_argument("output", type=Path)
    ap.add_argument("--text", default=TEXT)
    a=ap.parse_args()
    a.output.write_text(generate(a.font,a.text))
